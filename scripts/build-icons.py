"""Export Google's pinned Rounded variable font at the design system axes.

Usage: python3 scripts/build-icons.py /path/to/MaterialSymbolsRounded.ttf
Requires fonttools==4.67.0. Output is checked in; normal builds need no Python.
"""
import hashlib
import json
from pathlib import Path
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

root = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1])
assert hashlib.sha256(source.read_bytes()).hexdigest() == '32e4011709e055596eb8d2dd0f7cb547b47c1d40ac9ecb8fad54f7f7eac202e7', 'Font does not match pinned revision'
font = TTFont(source)
assert font['head'].unitsPerEm == 960
axes = {'FILL': 0, 'wght': 400, 'GRAD': 0, 'opsz': 24}
glyphs = font.getGlyphSet(location=axes)
cmap = font.getBestCmap()
output = root / 'public/icons/material-symbols-rounded'
output.mkdir(parents=True, exist_ok=True)
names = []
for line in (root / 'scripts/material-rounded.codepoints').read_text().splitlines():
    name, codepoint = line.split()
    assert all(c.islower() or c.isdigit() or c == '_' for c in name)
    glyph = cmap[int(codepoint, 16)]
    pen = SVGPathPen(glyphs, ntos=lambda v: format(round(v, 3), 'g'))
    glyphs[glyph].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))
    d = pen.getCommands()
    assert d, name
    (output / f'{name}.json').write_text(json.dumps([d], separators=(',', ':')) + '\n')
    names.append(name)
names.sort()
(root / 'src/components/Icon/icon-names.ts').write_text(
    '// Generated by scripts/build-icons.py. Do not edit.\n'
    + 'export const iconNames = ' + json.dumps(names, indent=2) + ' as const\n'
    + 'export type IconName = typeof iconNames[number]\n')
(output / 'manifest.json').write_text(json.dumps({
    'source': 'google/material-design-icons',
    'revision': '49d4db35df873165d6bd6ba09b063c7dafbac2f4',
    'fontSha256': hashlib.sha256(source.read_bytes()).hexdigest(),
    'axes': axes, 'count': len(names), 'viewBox': '0 -960 960 960',
}, indent=2) + '\n')
print(f'Exported {len(names)} Material Symbols Rounded icons at {axes}')
